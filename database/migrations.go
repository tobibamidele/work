package database

import (
	"context"
	"embed"
	"fmt"
	"io/fs"

	"github.com/google/uuid"
	"github.com/tobibamidele/lathe"
	"github.com/tobibamidele/lathe/migrate"
)

// MigrationsTable is the bookkeeping table Migrate uses. It is separate from
// Lathe's default lathe_migrations so the work table's migrations never mix
// with the application's own and cannot show up there as "missing".
const MigrationsTable = "work_migrations"

//go:embed migrations/postgres/*.sql migrations/mysql/*.sql migrations/sqlite/*.sql
var migrationFiles embed.FS

var zeroUUID = uuid.Nil

func migrationFS(db *lathe.DB) (fs.FS, error) {
	name := db.Dialect().Name()
	sub, err := fs.Sub(migrationFiles, "migrations/"+name)
	if err != nil {
		return nil, fmt.Errorf("work/database: no migrations for dialect %q: %w", name, err)
	}
	if _, err := fs.ReadDir(sub, "."); err != nil {
		return nil, fmt.Errorf("work/database: no migrations for dialect %q", name)
	}
	return sub, nil
}

// Migrate creates the work table and its indexes. It is idempotent and safe to
// call from every application instance at startup: Lathe's migration runner
// records applied versions with checksums and serializes concurrent runners
// with an advisory lock.
//
// The migrations are generated by Lathe from Tables(); use Migrate or add
// Tables() to your own Lathe schema, not both. db must not be bound to a
// transaction.
func Migrate(ctx context.Context, db *lathe.DB, opts ...migrate.Option) ([]migrate.Migration, error) {
	fsys, err := migrationFS(db)
	if err != nil {
		return nil, err
	}
	return migrate.Up(ctx, db, fsys, append([]migrate.Option{migrate.WithTable(MigrationsTable)}, opts...)...)
}

// MigrateDown reverts the newest steps migrations of the work table. Reverting
// the initial migration drops the table and every record in it.
func MigrateDown(ctx context.Context, db *lathe.DB, steps int, opts ...migrate.Option) ([]migrate.Migration, error) {
	fsys, err := migrationFS(db)
	if err != nil {
		return nil, err
	}
	return migrate.Down(ctx, db, fsys, steps, append([]migrate.Option{migrate.WithTable(MigrationsTable)}, opts...)...)
}

// MigrationStatus reports which work migrations are applied.
func MigrationStatus(ctx context.Context, db *lathe.DB, opts ...migrate.Option) ([]migrate.State, error) {
	fsys, err := migrationFS(db)
	if err != nil {
		return nil, err
	}
	return migrate.Status(ctx, db, fsys, append([]migrate.Option{migrate.WithTable(MigrationsTable)}, opts...)...)
}
